#!/usr/bin/env bash
# Foxalora Mail installer.
# Usage:
#   ./deploy/install.sh webmail.yourdomain.com --letsencrypt you@yourdomain.com   # real certificate
#   ./deploy/install.sh webmail.yourdomain.com --letsencrypt                      # same, no expiry emails
#   ./deploy/install.sh webmail.yourdomain.com --self-signed                      # testing only
#   ./deploy/install.sh webmail.yourdomain.com                                    # your own deploy/certs/*.pem
#
# Needs: a Linux server with Docker and Docker Compose v2, ports 80 and 443 open, and the domain's
# DNS A record pointing at this server (for --letsencrypt).
# What it does: creates deploy/.env with fresh random secrets, gets a TLS certificate, builds and
# starts the stack (Nginx, API, PostgreSQL, Valkey), runs migrations, and prints the link to the
# setup wizard, where the company, administrator, mail server and domains are entered in the browser.
# Safe to run again: secrets, certificates and data are kept.
#
# Email content is shown from a second host name on the same server (FOX-045), by default
# content.<domain>: give it a DNS record too. Another name: RENDER_DOMAIN=name ./deploy/install.sh ...
set -euo pipefail
START=$(date +%s)

DOMAIN="${1:-}"
CERT_MODE="own"
LE_EMAIL=""
case "${2:-}" in
  --self-signed) CERT_MODE="self-signed" ;;
  --letsencrypt) CERT_MODE="letsencrypt"; LE_EMAIL="${3:-}" ;;
  "") ;;
  *) echo "Unknown option: $2" >&2; exit 2 ;;
esac

usage() { sed -n '3,7p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 1; }
[ -n "$DOMAIN" ] || usage
# A plain host name only: letters, digits, dots and hyphens (it ends up in Nginx config and URLs).
[[ "$DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]] \
  || { echo "Not a valid host name: $DOMAIN" >&2; exit 1; }
# The email is optional: Let's Encrypt only uses it for expiry warnings; renew-cert.sh renews anyway.
if [ "$CERT_MODE" = letsencrypt ] && [ -n "$LE_EMAIL" ] && [[ ! "$LE_EMAIL" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]]; then
  echo "Not a valid email address: $LE_EMAIL (or leave it out: --letsencrypt alone)" >&2; exit 1
fi

# FOX-045: separate host name that shows email bodies, so they never run on the webmail's origin.
RENDER_DOMAIN_ARG="${RENDER_DOMAIN:-}"
RENDER_DOMAIN="${RENDER_DOMAIN_ARG:-content.${DOMAIN}}"
[[ "$RENDER_DOMAIN" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)+$ ]] \
  || { echo "Not a valid host name for RENDER_DOMAIN: $RENDER_DOMAIN" >&2; exit 1; }
[ "$RENDER_DOMAIN" != "$DOMAIN" ] || { echo "RENDER_DOMAIN must differ from $DOMAIN" >&2; exit 1; }

cd "$(dirname "$0")"
step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing requirement: $1" >&2; exit 1; }; }
need docker
need openssl
docker info >/dev/null 2>&1 || { echo "Docker is not running, or this user may not use it (try sudo)." >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required (the 'docker compose' plugin)." >&2; exit 1; }
COMPOSE=(./compose.sh)

step "Secrets"
if [ ! -f .env ]; then
  (
    umask 077
    cat > .env <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%d). Keep private and back it up: losing
# VAULT_KEYS only signs users out, losing the database passwords locks you out of your data.
DOMAIN=${DOMAIN}
# Second host name on this server that shows email content (needs its own DNS record).
RENDER_DOMAIN=${RENDER_DOMAIN}
POSTGRES_PASSWORD=$(openssl rand -hex 24)
APP_DB_PASSWORD=$(openssl rand -hex 24)
VALKEY_PASSWORD=$(openssl rand -hex 24)
VAULT_KEYS=k1:$(openssl rand -base64 32)
# Encrypts stored secrets such as administrators' two-step verification keys. Back it up with the database.
MASTER_KEYS=m1:$(openssl rand -base64 32)
# One-time key for the browser setup wizard (/setup). Useless once setup is done.
SETUP_TOKEN=$(openssl rand -hex 32)
SESSION_IDLE_MINUTES=30
SESSION_MAX_HOURS=12
EOF
  )
  echo "Created deploy/.env with new random secrets."
else
  CURRENT=$(sed -n 's/^DOMAIN=//p' .env)
  if [ "$CURRENT" != "$DOMAIN" ]; then
    echo "deploy/.env is for $CURRENT, not $DOMAIN. Edit DOMAIN in deploy/.env (and replace deploy/certs) to change it." >&2
    exit 1
  fi
  echo "deploy/.env already exists; keeping it."
  # Installs from before the setup wizard: add its token.
  grep -q '^SETUP_TOKEN=' .env || echo "SETUP_TOKEN=$(openssl rand -hex 32)" >> .env
  # Installs from before the admin console: add the key for stored secrets.
  grep -q '^MASTER_KEYS=' .env || { echo "MASTER_KEYS=m1:$(openssl rand -base64 32)" >> .env; echo "Added MASTER_KEYS to deploy/.env (back it up)."; }
  # Installs from before the render host: turned on only when asked (it needs DNS and a certificate).
  if grep -q '^RENDER_DOMAIN=' .env; then
    RENDER_DOMAIN=$(sed -n 's/^RENDER_DOMAIN=//p' .env)
  elif [ -n "$RENDER_DOMAIN_ARG" ]; then
    echo "RENDER_DOMAIN=${RENDER_DOMAIN}" >> .env
    echo "Added RENDER_DOMAIN=${RENDER_DOMAIN} to deploy/.env."
  else
    RENDER_DOMAIN=""
    echo "Note: email content is still shown on ${DOMAIN} itself. To use a separate address (recommended):"
    echo "  add a DNS record for content.${DOMAIN}, then run: RENDER_DOMAIN=content.${DOMAIN} $0 ${DOMAIN} ${2:-}"
    echo "  (the certificate must cover both names; see docs/runbooks/install.md)"
  fi
fi
NAMES=("$DOMAIN")
[ -z "$RENDER_DOMAIN" ] || NAMES+=("$RENDER_DOMAIN")

step "TLS certificate"
mkdir -p certs acme
# The certificate must name every host this server answers for.
covers_all() {
  local n
  for n in "${NAMES[@]}"; do
    openssl x509 -in certs/fullchain.pem -noout -checkhost "$n" 2>/dev/null | grep -q 'does match' || return 1
  done
}
if [ -s certs/fullchain.pem ] && [ -s certs/privkey.pem ] && { [ "$CERT_MODE" = own ] || covers_all; }; then
  echo "Using the existing certificate in deploy/certs/."
  covers_all || echo "Warning: the certificate in deploy/certs/ does not cover all of: ${NAMES[*]}. Browsers will refuse the missing names." >&2
elif [ "$CERT_MODE" = self-signed ]; then
  SAN=$(printf 'DNS:%s,' "${NAMES[@]}")
  openssl req -x509 -nodes -newkey rsa:2048 -days 30 \
    -keyout certs/privkey.pem -out certs/fullchain.pem \
    -subj "/CN=${DOMAIN}" -addext "subjectAltName=${SAN%,}" >/dev/null 2>&1
  chmod 600 certs/privkey.pem
  echo "Created a 30-day self-signed certificate. Browsers will warn. Testing only."
elif [ "$CERT_MODE" = letsencrypt ]; then
  # Port 80 must be free for the one-off challenge; the web container is not running yet on a first install.
  "${COMPOSE[@]}" stop web >/dev/null 2>&1 || true
  if [ -n "$LE_EMAIL" ]; then LE_ACCOUNT=(-m "$LE_EMAIL"); else LE_ACCOUNT=(--register-unsafely-without-email); fi
  LE_NAMES=()
  for n in "${NAMES[@]}"; do LE_NAMES+=(-d "$n"); done
  # --expand adds the render name to a certificate issued before it existed.
  docker run --rm -p 80:80 -v "$PWD/letsencrypt:/etc/letsencrypt" certbot/certbot:v5.9.0 \
    certonly --standalone --non-interactive --agree-tos --expand --cert-name "$DOMAIN" "${LE_ACCOUNT[@]}" "${LE_NAMES[@]}"
  # The certificate folder belongs to root (written by the certbot container), so copy inside a container.
  docker run --rm -v "$PWD/letsencrypt:/etc/letsencrypt:ro" -v "$PWD/certs:/certs" --entrypoint sh certbot/certbot:v5.9.0 -c \
    "cp -L /etc/letsencrypt/live/$DOMAIN/fullchain.pem /certs/fullchain.pem && umask 077 && cp -L /etc/letsencrypt/live/$DOMAIN/privkey.pem /certs/privkey.pem"
  echo "Let's Encrypt certificate installed. It expires in 90 days: set up daily renewal as root:"
  echo "  ( sudo crontab -l 2>/dev/null; echo \"17 3 * * * $PWD/renew-cert.sh >> /var/log/foxalora-cert.log 2>&1\" ) | sudo crontab -"
else
  echo "No certificate in deploy/certs/ (fullchain.pem and privkey.pem)." >&2
  echo "Re-run with --letsencrypt [you@yourdomain.com], or --self-signed for a quick test." >&2
  exit 1
fi

step "Build and start (the first build takes a few minutes)"
"${COMPOSE[@]}" up -d --build

printf 'Waiting for the API'
for _ in $(seq 1 60); do
  if [ "$(docker inspect -f '{{.State.Health.Status}}' "$("${COMPOSE[@]}" ps -q api)" 2>/dev/null)" = healthy ]; then
    echo " ok"; break
  fi
  printf '.'; sleep 2
done
[ "$(docker inspect -f '{{.State.Health.Status}}' "$("${COMPOSE[@]}" ps -q api)" 2>/dev/null)" = healthy ] \
  || { echo " not healthy. Check: ./deploy/compose.sh logs api migrate" >&2; exit 1; }

step "Setup"
SETUP=$("${COMPOSE[@]}" --profile tools run --rm -T cli setup:status | tail -1)
if [ "$SETUP" = open ]; then
  NEXT="Next: open the setup wizard in your browser and follow the steps (company, administrator,
mail server with a connection test, email domains). The link works until setup is finished:

  https://${DOMAIN}/setup#token=$(sed -n 's/^SETUP_TOKEN=//p' .env)

Keep this link private: whoever opens it first can set up this server."
else
  NEXT="Setup was completed earlier; the setup wizard is locked.
Mail servers and domains: ./deploy/cli.sh server:list <tenantId>   (tenant ids: ./deploy/cli.sh tenant:list)"
fi
echo "$SETUP"

MINUTES=$(( ($(date +%s) - START + 59) / 60 ))
cat <<EOF

Foxalora is running at https://${DOMAIN}   (install took about ${MINUTES} min)
${RENDER_DOMAIN:+Email content is shown from https://${RENDER_DOMAIN} (its DNS record must point at this server too).}

${NEXT}

Status : ./deploy/compose.sh ps
Logs   : ./deploy/compose.sh logs -f api
Stop   : ./deploy/compose.sh down
Testers: ./deploy/testing/enable.sh   (test mail server + password gate, see docs/runbooks/install.md)
Back up deploy/.env and the database volume.
EOF
